--[[
	SlimeSetup (generated by slimes/tools/build_slimes.py; edit that, not this file)

	1. Import the .glb files with File > Import 3D. Keep the model names (LilGreen, BlueBlob, ...).
	2. Select the imported slimes (or select nothing to scan Workspace, ReplicatedStorage and
	   ServerStorage), paste this whole file into the Command Bar and press Enter.

	For each slime model it:
	  - colours every part and sets its material and transparency
	  - moves the parts straight under the model and welds them to Body (the PrimaryPart)
	  - puts the pivot at the bottom centre, turned so the pivot's LookVector is the way the face looks
	  - scales the model to its size in studs
	  - adds Rarity and Size attributes

	Running it again is safe. A model is only touched when every part in it is a known slime part,
	so other models that happen to be called King or Ghost are left alone.
]]

